public class Point3D {
    
    public double x;
    public double y;
    public double z;
    public double w;

    public Point3D() { }

    public Point3D(double x, double y, double z, double w) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.w = w;
    }
}
